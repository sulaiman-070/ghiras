export function getAthkarByCategory(category, subCategory = null) {
  return ATHKAR_DUAS.filter(item => {
    if (item.category !== category) return false;
    if (subCategory && subCategory !== 'all' && item.subCategory) {
      return item.subCategory === subCategory || item.subCategory === 'جميع الصلوات';
    }
    return true;
  });
}
